def _has_death_cert(attachments: list[str]) -> bool:
    joined = " ".join(attachments).lower()
    return "death" in joined and "cert" in joined


def _has_certified_cert(attachments: list[str]) -> bool:
    """Institutions that demand a CERTIFIED death certificate mean it — a
    photocopy comes back with a reminder, which is exactly what makes the
    finite certified copies in the vault a real constraint."""
    joined = " ".join(attachments).lower()
    return "certified" in joined and "death" in joined and "cert" in joined


def _is_written_letter(channel: str) -> bool:
    return channel in ("letter", "mailed_letter")


@dataclass
class _Reply:
    delay_days: int
    subject: str
    body: str
    next_stage: str
    silent: bool = False  # institution does not respond at all


@dataclass
class ScheduledDelivery:
    due: str  # ISO date
    institution_id: str
    subject: str
    body: str
    task_id: str | None = None
    skip_if_stage: str | None = None  # skip when the stage key already equals this
    stage_key: str | None = None
    extra: dict = field(default_factory=dict)


class SimWorld:
    """Deterministic behavior engine + scheduled delivery queue."""

    _queue_lock = threading.Lock()  # guards the shared delivery queue's read-modify-write

    def __init__(self, ledger: Ledger) -> None:
        self.ledger = ledger

    # -- stage bookkeeping -------------------------------------------------

    def _stage_key(self, institution_id: str, task_id: str | None) -> str:
        return f"sim:stage:{institution_id}:{task_id or 'general'}"

    def get_stage(self, institution_id: str, task_id: str | None) -> str:
        return self.ledger.kv_get(self._stage_key(institution_id, task_id), "new") or "new"

    def set_stage(self, institution_id: str, task_id: str | None, stage: str) -> None:
        self.ledger.kv_set(self._stage_key(institution_id, task_id), stage)
        # Also track the institution's latest stage regardless of task, so scheduled
        # world events (like renewal reminders) can be suppressed once a matter is settled.
        self.ledger.kv_set(f"sim:inststage:{institution_id}", stage)

    # -- delivery queue ----------------------------------------------------

    def _queue(self) -> list[dict]:
        raw = self.ledger.kv_get("sim:queue", "[]") or "[]"
        return json.loads(raw)

    def _save_queue(self, queue: list[dict]) -> None:
        self.ledger.kv_set("sim:queue", json.dumps(queue))

    def schedule(self, case_id: str, delivery: ScheduledDelivery) -> None:
        with self._queue_lock:
            queue = self._queue()
            queue.append({"case_id": case_id, **delivery.__dict__})
            self._save_queue(queue)

    def deliver_due(self, case_id: str) -> list[MailMessage]:
        """Move every due scheduled reply into the case inbox. Called by the Vigil each cycle."""
        with self._queue_lock:
            return self._deliver_due_locked(case_id)

    def _deliver_due_locked(self, case_id: str) -> list[MailMessage]:
        today = self.ledger.sim_today()
        queue = self._queue()
        keep, delivered = [], []
        for item in queue:
            if item.get("case_id") != case_id or date.fromisoformat(item["due"]) > today:
                keep.append(item)
                continue
            if item.get("skip_if_stage") and item.get("stage_key"):
                if (self.ledger.kv_get(item["stage_key"], "new") or "new") == item["skip_if_stage"]:
                    continue  # event no longer applies (e.g. renewal already handled)
            inst = INSTITUTIONS[item["institution_id"]]
            subject, body = item["subject"], item["body"]
            if (item.get("extra") or {}).get("event") == "fraud_attempt":
                # The outcome genuinely depends on what the agent did: only a placed
                # deceased alert (any bureau brought to stage "done") stops the thief.
                subject, body = self._fraud_attempt_outcome()
            mail = MailMessage(
                case_id=case_id,
                direction="inbound",
                institution_id=inst.id,
                institution_name=inst.name,
                subject=subject,
                body=body,
                task_id=item.get("task_id"),
                sim_date=today,
            )
            self.ledger.save_mail(mail)
            self.ledger.record(
                case_id,
                actor="Postal service",
                kind="mail_received",
                summary=f"Reply arrived from {inst.name}: “{subject}”",
                detail=body,
                task_id=item.get("task_id"),
            )
            delivered.append(mail)
        self._save_queue(keep)
        return delivered

    # -- submission --------------------------------------------------------

    def submit(
        self,
        case_id: str,
        task_id: str | None,
        institution_id: str,
        channel: str,
        subject: str,
        body: str,
        attachments: list[str],
        payment_amount_usd: float = 0,
    ) -> str:
        """Epilogue sends something to an institution. Returns a human-readable receipt."""
        inst = INSTITUTIONS.get(institution_id)
        if inst is None:
            known = ", ".join(sorted(INSTITUTIONS))
            return f"ERROR: unknown institution '{institution_id}'. Known institutions: {known}"

        today = self.ledger.sim_today()
        outbound = MailMessage(
            case_id=case_id,
            direction="outbound",
            institution_id=inst.id,
            institution_name=inst.name,
            channel=channel,
            subject=subject,
            body=body,
            task_id=task_id,
            status="sent",
            sim_date=today,
        )
        self.ledger.save_mail(outbound)

        stage = self.get_stage(inst.id, task_id)
        reply = self._respond(inst, stage, channel, body, attachments, payment_amount_usd)
        if reply is None:
            return f"Delivered to {inst.name} via {channel}. No immediate acknowledgment."
        self.set_stage(inst.id, task_id, reply.next_stage)
        if reply.silent:
            return (
                f"Delivered to {inst.name} via {channel}. The portal accepted the request "
                f"but issued no confirmation number."
            )
        self.schedule(
            case_id,
            ScheduledDelivery(
                due=(today + timedelta(days=reply.delay_days)).isoformat(),
                institution_id=inst.id,
                subject=reply.subject,
                body=reply.body,
                task_id=task_id,
            ),
        )
        return (
            f"Delivered to {inst.name} via {channel}. They typically respond within "
            f"{reply.delay_days} day(s)."
        )

    # -- behavior scripts --------------------------------------------------

    def _respond(
        self, inst: Institution, stage: str, channel: str, body: str, attachments: list[str],
        payment_amount_usd: float = 0,
    ) -> _Reply | None:
        handler = getattr(self, f"_script_{inst.script}")
        if inst.script in ("ssa", "telecom"):
            return handler(inst, stage, channel, body, attachments, payment_amount_usd)
        return handler(inst, stage, channel, body, attachments)

