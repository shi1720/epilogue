"""The simulated institutions Epilogue corresponds with.

Every institution here is fictional (the Social Security Administration is
modeled generically as "the federal benefits agency" under a simulated
stand-in). Each has a small state machine that mirrors how such organizations
really behave after a death notification: they demand certified documents,
take days to answer, sometimes never answer at all, occasionally bill the
dead, and — in the case of credit bureaus — quietly catch identity thieves
trying to open accounts in a dead person's name.

Replies are not generated by an LLM. They are deterministic scripts, which
keeps the *world* honest while the *agent* stays fully model-driven — the
same discipline you'd use to evaluate any autonomous system.
"""

